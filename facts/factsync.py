#!/usr/bin/env python3
"""Keep every CV, statement, letter and draft in sync with facts/facts.toml.

    python3 facts/factsync.py build          # regenerate modules/facts.tex and facts/FACTS.md
    python3 facts/factsync.py fix [--dry]    # rewrite LAK status phrases in prose files
    python3 facts/factsync.py check [--style]  # list retired numbers / stale status (+ style)
    python3 facts/factsync.py rebuild        # recompile every CV + statement, print page counts
    python3 facts/factsync.py all [--rebuild]  # build, fix, check (then rebuild)

`check` exits with status 1 when it finds a retired number or a stale status phrase,
so it can gate a build script.
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "facts" / "facts.toml"
TEX_OUT = ROOT / "modules" / "facts.tex"
MD_OUT = ROOT / "facts" / "FACTS.md"

LAK_CONTEXT = r"(?=[^.\n]{0,120}(?:LAK 2027|Learning Analytics))"
STATUS_WORDS = {
    "under_review": r"under review",
    "accepted": r"accepted",
    "rejected": r"(?:under review|accepted)",
}


def load() -> dict:
    with FACTS.open("rb") as fh:
        return tomllib.load(fh)


def camel(*parts: str) -> str:
    out = ""
    for part in parts:
        for word in re.split(r"[_\W]+", part):
            if word:
                out += word[0].upper() + word[1:]
    if re.search(r"\d", out):
        raise SystemExit(f"macro name would contain a digit: {out}")
    return out


def tex_escape(value: str) -> str:
    # "--" date ranges are already TeX; only escape characters TeX treats specially.
    return (value.replace("\\", r"\textbackslash{}")
                 .replace("&", r"\&").replace("%", r"\%")
                 .replace("#", r"\#").replace("_", r"\_")
                 .replace("<", r"\textless{}").replace(">", r"\textgreater{}"))


def flat_values(data: dict) -> list[tuple[str, str, str]]:
    """(macro, value, comment) for every scalar in the simple tables, plus the status phrases."""
    rows = []
    for table in ("edu", "exp", "trace", "lak"):
        for key, value in data[table].items():
            rows.append((r"\fact" + camel(table, key), str(value), f"[{table}] {key}"))
    status = data["lak"]["status"]
    phrases = data["lak_phrases"].get(status) or data["lak_phrases"]["under_review"]
    for key, value in phrases.items():
        rows.append((r"\fact" + camel("lak", key), value, f"[lak_phrases.{status}] {key}"))
    return rows


def build(data: dict) -> None:
    rows = flat_values(data)
    lines = [
        "% GENERATED by facts/factsync.py from facts/facts.toml. Do not edit by hand.",
        f"% Updated {data['meta']['updated']}. LAK status: {data['lak']['status']}.",
        "% Usage in a CV: \\factLakMerge, \\factExpYears, \\factLakIs ... (see facts/FACTS.md).",
    ]
    for macro, value, comment in rows:
        lines.append(f"\\providecommand{{{macro}}}{{}}\\renewcommand{{{macro}}}{{{tex_escape(value)}}}  % {comment}")
    TEX_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    md = [
        "# Facts cheat sheet (generated)",
        "",
        f"Generated from `facts/facts.toml` on {data['meta']['updated']}. Edit the TOML, never this file.",
        f"LAK status is **{data['lak']['status']}** (decision {data['lak']['decision_date']}).",
        "",
        "Copy numbers and phrases from here when writing a statement, form answer or email.",
        "CVs use the LaTeX macro in the first column, so they never need hand edits.",
        "",
        "| LaTeX macro | Value | Source key |",
        "|---|---|---|",
    ]
    for macro, value, comment in rows:
        md.append(f"| `{macro}` | {value.replace('|', '/')} | {comment} |")
    md += ["", "## Retired (never use)", ""]
    for item in data["retired"]:
        md.append(f"- `{item['pattern']}`: {item['why']}")
    MD_OUT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {TEX_OUT.relative_to(ROOT)} ({len(rows)} macros) and {MD_OUT.relative_to(ROOT)}")


def scan_files(data: dict) -> list[Path]:
    cfg = data["scan"]
    exts = tuple(cfg["ext"])
    excl = cfg["exclude"]
    files = []
    for entry in cfg["include"]:
        base = ROOT / entry
        cands = [base] if base.is_file() else sorted(base.rglob("*"))
        for path in cands:
            if not path.is_file() or path.suffix not in exts:
                continue
            rel = path.relative_to(ROOT).as_posix()
            parts = rel.split("/")
            if any(rel == e or rel.startswith(e.rstrip("/") + "/") or e in parts for e in excl):
                continue
            files.append(path)
    return files


def transitions(data: dict) -> list[tuple[re.Pattern, str]]:
    status = data["lak"]["status"]
    pairs = data.get("lak_transition", {}).get(status, [])
    out = []
    for pair in pairs:
        src = re.escape(pair["from"])
        if not pair.get("anywhere") and not pair["from"].endswith(")"):
            src += LAK_CONTEXT
        out.append((re.compile(src), pair["to"]))
    return out


def fix(data: dict, dry: bool) -> int:
    rules = transitions(data)
    if not rules:
        print(f"fix: nothing to rewrite for status '{data['lak']['status']}'")
        return 0
    changed = 0
    for path in scan_files(data):
        text = path.read_text(encoding="utf-8")
        new = text
        for rx, repl in rules:
            new = rx.sub(repl, new)
        if new != text:
            changed += 1
            rel = path.relative_to(ROOT)
            print(f"{'would fix' if dry else 'fixed'} {rel}")
            if not dry:
                path.write_text(new, encoding="utf-8")
    print(f"fix: {changed} file(s) {'to change' if dry else 'changed'}")
    return changed


def check(data: dict, style: bool) -> int:
    allow = set(data["scan"]["allow_retired"])
    status = data["lak"]["status"]
    stale = []
    if status == "accepted":
        stale.append(re.compile(r"under review" + LAK_CONTEXT))
    elif status == "rejected":
        stale.append(re.compile(STATUS_WORDS["rejected"] + LAK_CONTEXT))
    retired = [(re.compile(r["pattern"]), r["why"]) for r in data["retired"]]
    styles = [(re.compile(s["pattern"]), s["why"], tuple(s["ext"])) for s in data.get("style", [])]

    # In CVs these values must come from macros, so a typed-in copy is a problem.
    macros = {comment.split("] ")[0][1:] + "." + comment.split("] ")[1]: macro
              for macro, _, comment in flat_values(data)}
    literals = []
    for key in data["scan"].get("cv_macro_only", []):
        table, name = key.split(".")
        value = data[table][name] if table != "lak_phrases" else data["lak_phrases"][status][name]
        literal = tex_escape(str(value))
        literals.append((re.compile(r"(?<![\d.])" + re.escape(literal) + r"(?![\d])"),
                         macros.get(key) or macros.get(f"lak_phrases.{status}.{name}", "?")))
    cv_prefixes = tuple(data["scan"].get("cv_files", []))

    problems = warnings = 0
    for path in scan_files(data):
        rel = path.relative_to(ROOT).as_posix()
        is_cv = path.suffix == ".tex" and rel.startswith(cv_prefixes)
        for no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if path.suffix == ".tex" and line.lstrip().startswith("%"):
                continue
            hits = []
            if rel not in allow:
                hits += [f"RETIRED ({why})" for rx, why in retired if rx.search(line)]
            hits += [f"STALE LAK STATUS (status is {status})" for rx in stale if rx.search(line)]
            if is_cv:
                hits += [f"TYPED VALUE in a CV: use {macro}" for rx, macro in literals if rx.search(line)]
            for kind in hits:
                problems += 1
                print(f"{rel}:{no}: {kind}\n    {line.strip()[:160]}")
            if style:
                for rx, why, exts in styles:
                    if path.suffix in exts and (m := rx.search(line)):
                        warnings += 1
                        print(f"{rel}:{no}: style: {why} [{m.group(0)}]")
    print(f"check: {problems} problem(s)" + (f", {warnings} style warning(s)" if style else ""))
    return problems


def rebuild(data: dict) -> int:
    """Compile every CV and statement listed in [scan].rebuild and report page counts."""
    import subprocess
    failed = 0
    for rel in data["scan"].get("rebuild", []):
        tex = ROOT / rel
        if not tex.exists():
            print(f"missing {rel}")
            failed += 1
            continue
        run = subprocess.run(["latexmk", "-g", "-xelatex", "-interaction=nonstopmode",
                              "-halt-on-error", tex.name], cwd=tex.parent,
                             capture_output=True, text=True)
        pdf = tex.with_suffix(".pdf")
        pages = "?"
        if pdf.exists():
            info = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True).stdout
            pages = next((l.split()[-1] for l in info.splitlines() if l.startswith("Pages")), "?")
        print(f"{'ok  ' if run.returncode == 0 else 'FAIL'} {pages:>2} p  {rel}")
        failed += run.returncode != 0
    print("Check that no entry or heading is split across a page break.")
    return failed


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in {"build", "fix", "check", "all", "rebuild"}:
        print(__doc__)
        return 2
    data = load()
    cmd = argv[0]
    if cmd in ("build", "all"):
        build(data)
    if cmd in ("fix", "all"):
        fix(data, dry="--dry" in argv)
    if cmd in ("check", "all"):
        if check(data, style="--style" in argv):
            return 1
    if cmd == "rebuild" or (cmd == "all" and "--rebuild" in argv):
        return 1 if rebuild(data) else 0
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
